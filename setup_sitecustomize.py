def find_repo_root() -> Path:
    """Best-effort: the Hermes checkout the launchers actually bind."""
    default = Path.home() / ".hermes" / "hermes-agent"
    launcher = default / ".hermes" / "bin" / "hermes"
    try:
        match = re.search(r"(/[\w./+-]*/hermes-agent)", launcher.read_text())
        if match:
            return Path(match.group(1))
    except OSError:
        pass
    return default


def store_pythons() -> list[Path]:
    return sorted((Path.home() / ".hermes" / "tools").glob("python-*/bin/python3"))


def site_packages_of(python: Path) -> Path | None:
    try:
        out = subprocess.run(
            [str(python), "-c", "import sysconfig; print(sysconfig.get_paths()['purelib'])"],
            capture_output=True, text=True, timeout=30, check=True,
        )
        candidate = Path(out.stdout.strip())
        return candidate if candidate.is_dir() else None
    except Exception:
        return None


def find_active_sitecustomize() -> Path | None:
    """Legacy path: the sitecustomize.py the RUNNING Python would import."""
    spec = importlib.util.find_spec("sitecustomize")
    if spec and spec.origin:
        return Path(spec.origin)
    for sp in site.getsitepackages():
        p = Path(sp)
        if p.is_dir():
            return p / "sitecustomize.py"
    return None


def _write(target: Path, bootstrap: str) -> str:
    if target.exists():
        content = target.read_text()
        if bootstrap.strip() in content:
            return "already current"
        keep = [line for line in content.splitlines(keepends=True)
                if not any(artifact in line for artifact in _OLD_ARTIFACTS)]
        cleaned = "".join(keep).strip()
        target.write_text((cleaned + "\n\n" if cleaned else "") + bootstrap)
        return "replaced"
    target.write_text(bootstrap)
    return "created"


def main() -> int:
    repo = None
    argv = sys.argv[1:]
    if "--repo-root" in argv:
        repo = Path(argv[argv.index("--repo-root") + 1]).expanduser()
    elif argv and not argv[0].startswith("-"):
        repo = Path(argv[0]).expanduser()
    if repo is None:
        repo = find_repo_root()

    targets = [(py, sp) for py in store_pythons() if (sp := site_packages_of(py))]

    if targets:
        if not repo.is_dir():
            print(f"WARNING: repo root not found at {repo}; installing the bootstrap anyway "
                  "(it no-ops until the checkout exists).", file=sys.stderr)
        bootstrap = BOOTSTRAP_PM.replace("__REPO__", str(repo))
        for py, sp in targets:
            target = sp / "sitecustomize.py"
            print(f"[{_write(target, bootstrap)}] {target}  (for {py})")
    else:
        target = find_active_sitecustomize()
        if target is None:
            print("ERROR: no PM store Python found, and the running Python imports no "
                  "sitecustomize — cannot determine an install target.", file=sys.stderr)
            return 1
        print(f"[{_write(target, BOOTSTRAP_LEGACY)}] {target}  (legacy mode)")

    print("Restart the gateway for the change to take effect.")
    print("Re-run this script after any update that recreates the Python runtime "
          "(hermes update / PM toolchain updates).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
