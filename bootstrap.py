#!/usr/bin/env python3
"""Startup bootstrap for the Doppler secret source (stdlib only).

Hermes loads ``.env`` at import time — before plugin discovery — so a
plugin-registered secret source is absent from that first load: the process
logs ``secrets.sources names unknown source(s): doppler`` and boots without
vault secrets until the post-discovery refresh runs.

The cure is to register the source at interpreter startup from a
``sitecustomize.py`` inside the runtime's own ``site-packages``.  That file has
to be (re)written whenever the Python runtime is recreated (``hermes update``,
PM toolchain updates), which used to be a manual step after every update.

This module owns the block and the write logic.  It is loaded by path from:

- ``__init__.py`` — self-heal on plugin load, so the first runtime boot after
  an update installs it for every process that follows, and
- ``setup_sitecustomize.py`` — explicit install (e.g. to make the very next
  boot warning-free, or for a runtime Hermes has not booted yet).

Stdlib only: the setup script runs under interpreters that have no Hermes
checkout on ``sys.path``.
"""

from __future__ import annotations

import os
import sys
import sysconfig
from pathlib import Path

MARKER = "# hermes-doppler: auto-registered DopplerSource"

# Lines from older bootstrap versions; stripped before a rewrite so updates
# never leave duplicated blocks behind.
OLD_ARTIFACTS = (
    MARKER,
    "# Auto-generated by hermes-doppler plugin",
    "import importlib.util as _ilu",
    "from pathlib import Path as _P",
    'spec_from_file_location("doppler_secrets"',
    "spec_from_file_location('doppler_secrets'",
    "register_source(_m.DopplerSource())",
    "register_source(_mod.DopplerSource())",
    "from agent.secret_sources.registry import register_source",
    "import sys as _sys",
    "_hermes_doppler_path",
    "_hermes_doppler_repo",
    "_hermes_doppler_env",
    "_hermes_doppler_plugin",
    "_hermes_doppler_dir",
    "_hermes_doppler_spec",
    "_hermes_doppler_mod",
    "_hermes_doppler_register",
    "_hermes_doppler_get",
    "from pm.environments import",
)

BOOTSTRAP_PM = '''\
# hermes-doppler: auto-registered DopplerSource
# Auto-generated by hermes-doppler plugin — registers the Doppler secret
# source before load_hermes_dotenv() runs. Safe to delete; the plugin
# re-creates it on next setup.
#
# PM runtime: the managed store Python boots without the checkout or the
# install's dependency environment on sys.path; add both for the
# registration, then restore sys.path exactly as found.
import importlib.util as _ilu
import sys as _sys
from pathlib import Path as _P

_hermes_doppler_path = list(_sys.path)
try:
    _hermes_doppler_repo = _P("__REPO__")
    if _hermes_doppler_repo.is_dir() and str(_hermes_doppler_repo) not in _sys.path:
        _sys.path.insert(0, str(_hermes_doppler_repo))
    try:
        from pm.environments import selected_venv as _hermes_doppler_sel, site_packages as _hermes_doppler_sp
        _hermes_doppler_env = _hermes_doppler_sp(_hermes_doppler_sel(_hermes_doppler_repo))
        if _hermes_doppler_env.is_dir() and str(_hermes_doppler_env) not in _sys.path:
            _sys.path.insert(0, str(_hermes_doppler_env))
    except Exception:
        pass
    _hermes_doppler_plugin = None
    for _hermes_doppler_dir in (_P.home() / ".hermes" / "plugins" / "doppler-secrets",
                                _P.home() / ".hermes" / "plugins" / "doppler_secrets"):
        if (_hermes_doppler_dir / "__init__.py").exists():
            _hermes_doppler_plugin = _hermes_doppler_dir / "__init__.py"
            break
    if _hermes_doppler_plugin is not None:
        _hermes_doppler_spec = _ilu.spec_from_file_location("doppler_secrets", str(_hermes_doppler_plugin))
        _hermes_doppler_mod = _ilu.module_from_spec(_hermes_doppler_spec)
        _hermes_doppler_spec.loader.exec_module(_hermes_doppler_mod)
        from agent.secret_sources.registry import register_source as _hermes_doppler_register
        from agent.secret_sources.registry import get_source as _hermes_doppler_get
        _hermes_doppler_register(_hermes_doppler_mod.DopplerSource())
        _hermes_doppler_get("doppler")  # warm the one-shot lazy builtin load under the dependency env
except Exception:
    pass
finally:
    _sys.path[:] = _hermes_doppler_path
'''

BOOTSTRAP_LEGACY = '''\
# hermes-doppler: auto-registered DopplerSource
# Auto-generated by hermes-doppler plugin — registers the Doppler secret
# source before load_hermes_dotenv() runs. Safe to delete; the plugin
# re-creates it on next setup.
import importlib.util as _ilu
from pathlib import Path as _P
try:
    _home = _P.home() / ".hermes" / "plugins"
    _p = next((d / "__init__.py" for d in (_home / "doppler-secrets", _home / "doppler_secrets") if (d / "__init__.py").exists()), None)
    if _p:
        _s = _ilu.spec_from_file_location("doppler_secrets", str(_p))
        _m = _ilu.module_from_spec(_s)
        _s.loader.exec_module(_m)
        from agent.secret_sources.registry import register_source
        register_source(_m.DopplerSource())
except Exception:
    pass
'''


def block_for(repo_root, *, legacy: bool = False) -> str:
    """The sitecustomize block for one install layout."""
    if legacy:
        return BOOTSTRAP_LEGACY
    return BOOTSTRAP_PM.replace("__REPO__", str(repo_root))


def runtime_site_packages() -> Path | None:
    """``purelib`` of the running interpreter, but only for a Hermes-owned runtime.

    Refuses anything outside ``~/.hermes`` — a system Python or an unrelated
    venv is not ours to modify.
    """
    try:
        purelib = Path(sysconfig.get_paths()["purelib"])
    except Exception:
        return None
    try:
        purelib.resolve().relative_to((Path.home() / ".hermes").resolve())
    except (ValueError, OSError):
        return None
    return purelib if purelib.is_dir() else None


def write_block(target: Path, block: str) -> str:
    """Install *block* into *target*; returns created|replaced|current|unwritable.

    Existing content is preserved (only our own older blocks are stripped).
    Written through a temp file in the same directory so a concurrent reader
    never sees a partial file.
    """
    status = "created"
    payload = block
    if target.exists():
        try:
            content = target.read_text(encoding="utf-8", errors="replace")
        except OSError:
            return "unwritable"
        if block.strip() in content:
            return "current"
        keep = [line for line in content.splitlines(keepends=True)
                if not any(artifact in line for artifact in OLD_ARTIFACTS)]
        cleaned = "".join(keep).strip()
        payload = (cleaned + "\n\n" if cleaned else "") + block
        status = "replaced"

    tmp = target.with_name(f".{target.name}.{os.getpid()}.tmp")
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        tmp.write_text(payload, encoding="utf-8")
        os.replace(tmp, target)
    except OSError:
        try:
            tmp.unlink()
        except OSError:
            pass
        return "unwritable"
    return status


def ensure(*, repo_root, target=None, legacy: bool = False) -> str:
    """Make the bootstrap present for one runtime. Never raises.

    *target* is a site-packages directory; the default is the running
    interpreter's, when it is Hermes-owned (see :func:`runtime_site_packages`).
    """
    if not repo_root:
        return "skipped:no-repo-root"
    site_packages = Path(target) if target else runtime_site_packages()
    if site_packages is None:
        return "skipped:not-a-hermes-runtime"
    try:
        return write_block(site_packages / "sitecustomize.py", block_for(repo_root, legacy=legacy))
    except Exception:
        return "skipped:error"
