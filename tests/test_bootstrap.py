"""Tests for the startup-bootstrap installer (bootstrap.py).

Loaded by path: bootstrap.py is deliberately dependency-free and is imported the
same way from the plugin and from setup_sitecustomize.py.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

BOOTSTRAP_PATH = Path(__file__).resolve().parents[1] / "bootstrap.py"


def load_bootstrap():
    spec = importlib.util.spec_from_file_location("hermes_doppler_bootstrap", str(BOOTSTRAP_PATH))
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


bootstrap = load_bootstrap()


class TestBlockFor:
    def test_pm_block_embeds_repo_root(self):
        block = bootstrap.block_for("/opt/hermes-agent")
        assert '/opt/hermes-agent' in block
        assert bootstrap.MARKER in block

    def test_legacy_block_is_repo_free(self):
        block = bootstrap.block_for("/opt/hermes-agent", legacy=True)
        assert bootstrap.MARKER in block
        assert "/opt/hermes-agent" not in block


class TestWriteBlock:
    def test_creates_when_absent(self, tmp_path):
        target = tmp_path / "sitecustomize.py"
        assert bootstrap.write_block(target, "# block\n") == "created"
        assert target.read_text() == "# block\n"

    def test_current_is_idempotent(self, tmp_path):
        target = tmp_path / "sitecustomize.py"
        bootstrap.write_block(target, "# block\n")
        mtime = target.stat().st_mtime_ns
        assert bootstrap.write_block(target, "# block\n") == "current"
        assert target.stat().st_mtime_ns == mtime

    def test_preserves_foreign_content(self, tmp_path):
        target = tmp_path / "sitecustomize.py"
        target.write_text("# someone else's bootstrap\nimport os\n")
        assert bootstrap.write_block(target, "# block\n") == "replaced"
        content = target.read_text()
        assert "someone else's bootstrap" in content
        assert content.rstrip().endswith("# block")

    def test_strips_older_generated_blocks(self, tmp_path):
        target = tmp_path / "sitecustomize.py"
        target.write_text("\n".join([
            bootstrap.MARKER,
            "# Auto-generated by hermes-doppler plugin",
            "import importlib.util as _ilu",
            "_hermes_doppler_path = list([])",
            "",
        ]))
        assert bootstrap.write_block(target, bootstrap.block_for("/repo")) == "replaced"
        content = target.read_text()
        assert content.count(bootstrap.MARKER) == 1
        # One copy of the bootstrap's imports survives — the freshly written block's.
        assert content.count("import importlib.util as _ilu") == 1

    def test_unwritable_directory_is_reported(self, tmp_path):
        target = tmp_path / "missing-parent" / "sitecustomize.py"
        target.parent.mkdir()
        target.parent.chmod(0o500)
        try:
            assert bootstrap.write_block(target, "# block\n") == "unwritable"
        finally:
            target.parent.chmod(0o700)


class TestEnsure:
    def test_installs_into_explicit_target(self, tmp_path):
        status = bootstrap.ensure(repo_root="/opt/hermes-agent", target=tmp_path)
        assert status == "created"
        written = (tmp_path / "sitecustomize.py").read_text()
        assert "/opt/hermes-agent" in written

    def test_requires_repo_root(self, tmp_path):
        assert bootstrap.ensure(repo_root=None, target=tmp_path) == "skipped:no-repo-root"
        assert not (tmp_path / "sitecustomize.py").exists()

    def test_refuses_foreign_runtime(self, tmp_path, monkeypatch):
        """Self-heal must never write into a system Python or an unrelated venv."""
        monkeypatch.setattr(bootstrap.Path, "home", classmethod(lambda cls: tmp_path))
        assert bootstrap.runtime_site_packages() is None
        assert bootstrap.ensure(repo_root="/repo") == "skipped:not-a-hermes-runtime"
